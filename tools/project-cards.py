TILE_BOTTOM = re.compile(
    r'\s*<div class="tile-bottom">\s*<div class="readiness-strip">.*?'
    r'(<span class="loc-bar">.*?</span>)\s*</div>', re.S)


def main():
    path = os.path.join(ROOT, PAGE)
    src = io.open(path, encoding='utf-8').read()

    long_texts, used, missing = [], {}, set()

    def fix(m):
        card = m.group(0)
        pct = re.search(r'<div class="readiness-pct">(\d+)%</div>', card)
        pct = pct.group(1) if pct else re.search(r'data-readiness="(\d+)"', card).group(1)

        # 1. готовность из-под фотографии — вниз карточки
        if 'ptile-progress' not in card:
            card = TILE_BOTTOM.sub(lambda b: '\n        ' + b.group(1), card)
            progress = (
                '\n      <div class="ptile-progress">'
                '<div class="readiness-bar"><div class="readiness-bar-fill" style="width:%s%%"></div></div>'
                '<div class="readiness-pct">%s%%</div></div>' % (pct, pct))
            card = card.replace('</a>', progress + '\n    </a>')

        # 2. своё описание вместо собранного из мета-данных
        name = re.search(r'<div class="pname">([^<]*)</div>', card)
        name = name.group(1).strip() if name else ''
        variants = DESCS.get(name)
        if not variants:
            missing.add(name)
        else:
            i = used.get(name, 0)
            used[name] = i + 1
            text = variants[i % len(variants)]
            if len(text) > LIMIT:
                long_texts.append((len(text), text))
            card = re.sub(r'(<div class="ptile-desc">)[^<]*(</div>)',
                          lambda d: d.group(1) + text + d.group(2), card, count=1)
        return card

    out = re.sub(r'<a class="ptile".*?</a>', fix, src, flags=re.S)
    io.open(path, 'w', encoding='utf-8', newline='').write(out)

    print('карточек: %d, описаний назначено: %d'
          % (out.count('<a class="ptile"'), sum(used.values())))
    if missing:
        print('НЕТ ОПИСАНИЯ:', ', '.join(sorted(missing)))
    if long_texts:
        print('длиннее %d знаков:' % LIMIT)
        for n, t in sorted(long_texts, reverse=True)[:10]:
            print('  %3d  %s' % (n, t))
    for name, cnt in used.items():
        if cnt > len(DESCS[name]):
            print('вариантов не хватило: %s (%d карточек, %d текстов)'
                  % (name, cnt, len(DESCS[name])))
    return 0


if __name__ == '__main__':
    sys.exit(main())
