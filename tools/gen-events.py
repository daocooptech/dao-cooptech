def people_form(n):
    """1 участник, 2 участника, 5 участников — как в остальных каталогах."""
    a, b = n % 10, n % 100
    if b in (11, 12, 13, 14):
        return "участников"
    if a == 1:
        return "участник"
    if a in (2, 3, 4):
        return "участника"
    return "участников"


def signed_form(n):
    a, b = n % 10, n % 100
    return "записался" if a == 1 and b != 11 else "записались"


def slug(text, n):
    base = re.sub(r"[^a-zа-яё0-9]+", "-", text.lower()).strip("-")[:32]
    return "ev-%s-%d" % (base, n)


def card(e):
    """Одна карточка. Разметка списана с написанных руками — специально."""
    past = e["date"] < TODAY
    d = "%d %s %d" % (e["date"].day, MONTHS[e["date"].month - 1], e["date"].year)
    tint = "var(--%s-tint)" % e["tint"]
    ink = "var(--gold-text)" if e["tint"] == "gold" else "var(--teal-dark)"
    if past:
        who = "👥 %d %s" % (e["n"], people_form(e["n"]))
        action = '<span class="button secondary" aria-disabled="true">Прошло</span>'
    else:
        who = "👥 %d %s" % (e["n"], signed_form(e["n"]))
        action = ('<button class="button secondary attend-btn" type="button" data-event="%s"'
                  ' data-event-name="«%s»">Записаться</button>' % (e["id"], e["title"]))
    return (
        '          <div class="vacancy-card" data-event="%s" data-category="%s" data-city="%s"'
        ' data-format="%s" data-year="%d" data-date="%s">\n'
        '            <div class="card-row">\n'
        '              <div class="img-wrap"><div class="logo-square" style="width:48px;height:48px;'
        'background:%s;color:%s;font-size:20px">%s</div><span class="loc-bar">📍 %s</span></div>\n'
        '              <div style="flex:1;min-width:0">\n'
        '                <div class="vacancy-title">%s</div>\n'
        '                <div class="vacancy-meta">🗓 %s, %s–%s<span class="meta-city"> · 📍 %s</span></div>\n'
        '                <p class="vacancy-snippet">%s</p>\n'
        '                <div class="vacancy-tags"><span class="chip">%s</span><span class="chip">%s</span></div>\n'
        '                <div class="vacancy-footer">\n'
        '                  <span class="vacancy-posted">%s</span>\n'
        '                  %s\n'
        '                </div>\n'
        '              </div>\n'
        '            </div>\n'
        '          </div>\n'
    ) % (e["id"], e["cat"], e["city"], e["fmt"], e["date"].year, e["date"].isoformat(),
         tint, ink, e["emoji"], e["city"], e["title"], d, e["t1"], e["t2"], e["city"],
         e["snippet"], e["cat"], e["fmt"], who, action)


def build():
    rnd = random.Random(20260909)
    cats = list(CATS)
    events, seen = [], set()
    plan = [(2025, 34), (2026, 52), (2027, 34)]
    i = 0
    for year, count in plan:
        made = 0
        guard = 0
        while made < count and guard < count * 40:
            guard += 1
            cat = rnd.choice(cats)
            emoji, tint, titles, snips = CATS[cat]
            online = rnd.random() < 0.28
            city = "Удалённо" if online else rnd.choice(CITIES)
            title = rnd.choice(titles).format(
                coop=rnd.choice(COOPS), community=rnd.choice(COMMUNITIES),
                city=rnd.choice(CITIES), year=year, n=rnd.randint(2, 9))
            key = (title, year)
            if key in seen:
                continue
            seen.add(key)
            t1, t2 = rnd.choice(TIMES)
            i += 1
            made += 1
            events.append({
                "id": slug(title, i), "cat": cat, "city": city,
                "fmt": "Онлайн" if online else "Офлайн",
                "date": datetime.date(year, rnd.randint(1, 12), rnd.randint(1, 28)),
                "t1": t1, "t2": t2, "emoji": emoji, "tint": tint,
                "title": title, "snippet": rnd.choice(snips),
                "n": rnd.randint(4, 180),
            })
    events.sort(key=lambda e: e["date"])
    return events


def main():
    s = io.open("ext-events.html", encoding="utf-8").read()
    events = build()
    block = BEGIN + "\n" + "".join(card(e) for e in events) + END + "\n"

    if BEGIN in s:
        s = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda m: block,
                   s, flags=re.S)
    else:
        anchor = '\n        </div>\n        <div class="empty-state" id="events-empty"'
        assert anchor in s, "не найден конец списка событий"
        s = s.replace(anchor, "\n" + block + anchor[1:], 1)

    # Прошедшие события, написанные руками, тоже приводим к состоянию «Прошло»:
    # иначе на одной странице соседствуют встреча 2025 года с кнопкой
    # «Записаться» и такая же с пометкой «Прошло».
    dates = dict(re.findall(r'data-event="([^"]+)"[^>]*data-date="([^"]+)"', s))
    fixed = 0
    for eid, iso in dates.items():
        if datetime.date(*map(int, iso.split("-"))) >= TODAY:
            continue
        pat = (r'<span class="vacancy-posted">👥 (\d+) записались</span>\n(\s*)'
               r'<button class="button secondary attend-btn" type="button" '
               r'data-event="' + re.escape(eid) + r'"[^>]*>Записаться</button>')

        def repl(m):
            n = int(m.group(1))
            return ('<span class="vacancy-posted">👥 %d %s</span>\n%s'
                    '<span class="button secondary" aria-disabled="true">Прошло</span>'
                    % (n, people_form(n), m.group(2)))

        s, k = re.subn(pat, repl, s)
        fixed += k
    if fixed:
        print("прошедших событий переведено в состояние «Прошло»:", fixed)

    hand = len(re.findall(r'class="vacancy-card" data-event="(?!ev-)', s))
    by_year = {}
    for e in events:
        by_year[e["date"].year] = by_year.get(e["date"].year, 0) + 1
    print("своих событий:", len(events), "· руками:", hand, "· всего:", len(events) + hand)
    print("по годам:", by_year)
    print("прошедших:", sum(1 for e in events if e["date"] < TODAY))
    print("длиннейший заголовок:", max(len(e["title"]) for e in events))
    print("длиннейшее описание:", max(len(e["snippet"]) for e in events))
    if CHECK:
        print("(пробный запуск, файл не тронут)")
        return
    io.open("ext-events.html", "w", encoding="utf-8", newline="\n").write(s)
    print("записано в ext-events.html")


main()
